"""The two server-rendered steps between the admin password and the admin itself.

Both are mounted by Admin2FASite.get_urls() under /admin/2fa/ and wrapped there
with never_cache, csrf_protect and sensitive_post_parameters("token").
Secrets (TOTP key, QR code, backup codes) only live in locals wrapped in
``Redacted``: a traceback sent to Sentry shows ``<redacted>``.
"""
import logging
import re
from base64 import b32encode
from urllib.parse import urlencode

import qrcode
import qrcode.image.svg
from django.contrib import messages
from django.contrib.auth.views import redirect_to_login
from django.db import transaction
from django.shortcuts import redirect
from django.template.response import TemplateResponse
from django.urls import reverse
from django.utils import timezone
from django.utils.http import url_has_allowed_host_and_scheme
from django.utils.safestring import mark_safe
from django.utils.translation import gettext as _
from django.utils.translation import ngettext
from django_otp import login as otp_login
from django_otp.plugins.otp_static.models import StaticDevice, StaticToken
from django_otp.plugins.otp_totp.models import TOTPDevice

from .forms import TokenForm
from .utils import (
    BACKUP_CODE_COUNT,
    STATIC_DEVICE_NAME,
    TOTP_DEVICE_NAME,
    Redacted,
    is_verified,
)

logger = logging.getLogger("admin_2fa")


def _next_url(request, site):
    target = request.POST.get("next") or request.GET.get("next")
    if target and url_has_allowed_host_and_scheme(
        target, allowed_hosts={request.get_host()}, require_https=request.is_secure()
    ):
        return target
    return reverse("admin:index", current_app=site.name)


def _otp_url(request, site, step):
    url = reverse(f"admin:2fa_{step}", current_app=site.name)
    return f"{url}?{urlencode({'next': _next_url(request, site)})}"


def _enrolled(user):
    """Enrolled = a confirmed TOTP device. Backup codes alone never count."""
    return TOTPDevice.objects.devices_for_user(user, confirmed=True).exists()


def redirect_to_otp(request, site):
    """Send a password-authenticated staff user to the right 2FA step."""
    step = "verify" if _enrolled(request.user) else "setup"
    return redirect(_otp_url(request, site, step))


def _gate(request, site):
    """Only password-authenticated, active staff without a verified session get in."""
    user = request.user
    if not (user.is_authenticated and user.is_active and user.is_staff):
        return redirect_to_login(request.get_full_path(), reverse("admin:login", current_app=site.name))
    if is_verified(user):
        return redirect(_next_url(request, site))
    return None


def _render(request, site, template, title, **extra):
    context = {
        **site.each_context(request),
        "title": title,
        "next": _next_url(request, site),
        **extra,
    }
    return TemplateResponse(request, template, context)


def _throttled_message(info):
    locked_until = (info or {}).get("locked_until")
    if locked_until is None:
        return _("Too many attempts. Wait a moment, then try again.")
    seconds = max(1, int((locked_until - timezone.now()).total_seconds()) + 1)
    return ngettext(
        "Too many failed attempts. Try again in %(n)d second.",
        "Too many failed attempts. Try again in %(n)d seconds.",
        seconds,
    ) % {"n": seconds}


def _qr_svg(device):
    image = qrcode.make(
        device.config_url,
        # White background: the code stays scannable when the admin is in dark mode.
        image_factory=qrcode.image.svg.SvgPathFillImage,
        box_size=10,
        border=2,
    )
    svg = image.to_string(encoding="unicode")
    # Fixed pixel size instead of millimetres, and a label for screen readers.
    svg = re.sub(
        r'^<svg width="[^"]+" height="[^"]+"',
        '<svg width="220" height="220" role="img" aria-label="QR code"',
        svg,
        count=1,
    )
    # Pure SVG markup (rect + path), generated by qrcode from our own data: no
    # user input, no script, no style attribute — fine under any CSP.
    return mark_safe(svg)


def _manual_key(device):
    """The key as authenticator apps expect it when typed by hand, in groups of 4."""
    key = b32encode(device.bin_key).decode("ascii").rstrip("=")
    return " ".join(key[i:i + 4] for i in range(0, len(key), 4))


def _replace_backup_codes(user):
    StaticDevice.objects.filter(user=user).delete()
    device = StaticDevice.objects.create(user=user, name=STATIC_DEVICE_NAME, confirmed=True)
    secret = [StaticToken.random_token() for _ in range(BACKUP_CODE_COUNT)]
    StaticToken.objects.bulk_create(StaticToken(device=device, token=code) for code in secret)
    return Redacted(secret)


def setup(request, site):
    """First admin login: scan the QR code, confirm one code, get the backup codes once."""
    denied = _gate(request, site)
    if denied:
        return denied
    user = request.user
    if _enrolled(user):
        # Enrolled already: re-enrolment only after `manage.py admin_2fa_reset`.
        return redirect(_otp_url(request, site, "verify"))

    device = TOTPDevice.objects.filter(user=user, confirmed=False).order_by("pk").first()
    if device is None:
        device = TOTPDevice.objects.create(user=user, name=TOTP_DEVICE_NAME, confirmed=False)

    form = TokenForm(request.POST or None)
    if request.method == "POST" and form.is_valid():
        secret = None
        with transaction.atomic():
            device = TOTPDevice.objects.select_for_update().get(pk=device.pk)
            allowed, info = device.verify_is_allowed()
            token = form.cleaned_data["token"]
            if not allowed:
                form.add_error(None, _throttled_message(info))
            elif device.verify_token(token):
                device.confirmed = True
                device.save(update_fields=["confirmed"])
                TOTPDevice.objects.filter(user=user, confirmed=False).delete()
                secret = _replace_backup_codes(user)
            else:
                form.add_error("token", _("Wrong code. Check the time on your phone and try again."))
        if secret is not None:
            otp_login(request, device)
            logger.info("admin_2fa: TOTP device enrolled for user id=%s", user.pk)
            # Rendered in the POST response itself, never stored: a reload
            # re-posts, finds the session verified and redirects — shown once.
            return _render(
                request, site, "admin_2fa/backup_codes.html",
                _("Two-factor authentication enabled"), codes=secret,
            )

    return _render(
        request, site, "admin_2fa/setup.html", _("Set up two-factor authentication"),
        form=form,
        secret=Redacted(_manual_key(device)),
        qr_svg=Redacted(_qr_svg(device)),
    )


def _match(user, token):
    """Return (device, throttle_info). A 6-digit code is TOTP, anything else a backup code.

    Routing by shape keeps a backup code from counting as a failed TOTP attempt
    (and the reverse). Each device keeps its own django-otp throttle.
    """
    model = TOTPDevice if (len(token) == 6 and token.isdigit()) else StaticDevice
    throttled = None
    with transaction.atomic():
        for device in model.objects.devices_for_user(user, confirmed=True).select_for_update():
            allowed, info = device.verify_is_allowed()
            if not allowed:
                throttled = info
                continue
            if device.verify_token(token):
                return device, None
    return None, throttled


def verify(request, site):
    """Every admin login after enrolment: the current TOTP code or one backup code."""
    denied = _gate(request, site)
    if denied:
        return denied
    user = request.user
    if not _enrolled(user):
        return redirect(_otp_url(request, site, "setup"))

    form = TokenForm(request.POST or None)
    if request.method == "POST" and form.is_valid():
        device, throttled = _match(user, form.cleaned_data["token"])
        if device is not None:
            otp_login(request, device)
            if isinstance(device, StaticDevice):
                left = device.token_set.count()
                logger.warning("admin_2fa: backup code used by user id=%s, %d left", user.pk, left)
                messages.warning(request, ngettext(
                    "Backup code used: %(n)d left. Lost your phone? Have your 2FA reset.",
                    "Backup code used: %(n)d left. Lost your phone? Have your 2FA reset.",
                    left,
                ) % {"n": left})
            return redirect(_next_url(request, site))
        logger.info("admin_2fa: failed second factor for user id=%s", user.pk)
        form.add_error(None, _throttled_message(throttled) if throttled else _("Invalid code."))

    return _render(request, site, "admin_2fa/verify.html", _("Two-factor authentication"), form=form)
